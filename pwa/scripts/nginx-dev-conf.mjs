#!/usr/bin/env node
// nginx site for the dev instance dev.permadesignkit.org (Werkstatt #656), derived from the live
// config so both never drift apart: same locations, caches and CSP, but its own web root, its own
// proxy process (port 8788, a copy of the live data) and the whole site behind a team/admin login.
// Only the HTTPS server block is taken (maps, caches and upstreams are defined once, by the live file).
//
//   node scripts/nginx-dev-conf.mjs > /etc/nginx/sites-available/dev.permadesignkit.org && nginx -t && systemctl reload nginx
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export function devConf(live) {
  const start = live.indexOf('server {');
  const end = live.indexOf('\n}\n', start);
  if (start < 0 || end < 0) throw new Error('no server block');
  let s = live.slice(start, end + 2);
  const swap = (from, to) => { if (!s.includes(from)) throw new Error(`missing: ${from}`); s = s.split(from).join(to); };
  swap('server_name permadesignkit.org;', 'server_name dev.permadesignkit.org;');
  swap('root /var/www/permadesignkit.org;', 'root /var/www/dev.permadesignkit.org;');
  swap('127.0.0.1:8787', '127.0.0.1:8788');
  swap('/etc/letsencrypt/live/permadesignkit.org/', '/etc/letsencrypt/live/dev.permadesignkit.org/');
  swap(' ipv6only=on', '');  // allowed once per address, the live block has it
  // Gated locations of the live site: on dev they need team/admin too.
  swap('auth_request /_pdk_auth;', 'auth_request /_pdk_team;');
  // Login and the auth/feature API must work before the login; the proxy checks /api/x/ and /api/admin/ itself.
  s = s.replace(/(location ~ \^\/api\/\(auth\|admin\|x\|beta\)\/ \{\n|location = \/api\/features \{\n|location = \/_pdk_auth \{\n)/g, '$1        auth_request off;\n');
  const gate = `
    # Dev instance (Werkstatt #656): everything only for team/admin accounts, except what the login page needs.
    auth_request /_pdk_team;
    error_page 401 = @pdk_login;
    add_header X-Robots-Tag "noindex, nofollow" always;
    location @pdk_login {
        auth_request off;
        return 302 /anmelden/?next=$request_uri;
    }
    location = /_pdk_team {
        internal;
        auth_request off;
        proxy_pass http://127.0.0.1:8788/api/auth/check?team;
        proxy_pass_request_body off;
        proxy_set_header Content-Length "";
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
    }
    location ^~ /_astro/ {
        auth_request off;
        try_files $uri =404;
    }
    location ~ ^/(anmelden/?|anmelden/index\\.html|boot\\.js|favicon\\.(svg|ico)|apple-touch-icon\\.png|manifest\\.json|icon-[a-z0-9-]+\\.png|fonts/.*)$ {
        auth_request off;
        try_files $uri $uri/index.html =404;
    }
    location = /robots.txt {
        auth_request off;
        return 200 "User-agent: *\\nDisallow: /\\n";
    }
`;
  swap('    index index.html;\n', `    index index.html;\n${gate}`);
  return `# GENERATED by pwa/scripts/nginx-dev-conf.mjs from permadesignkit.org.conf — do not edit, regenerate.\n${s}server {\n    listen 80;\n    listen [::]:80;\n    server_name dev.permadesignkit.org;\n    return 301 https://$host$request_uri;\n}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  process.stdout.write(devConf(readFileSync(new URL('../server/nginx/permadesignkit.org.conf', import.meta.url), 'utf8')));
}
